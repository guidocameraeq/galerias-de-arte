// tools/discover.mjs — barrido de descubrimiento (Met + Wikimedia).
// Devuelve hits normalizados (misma forma que resolve.mjs), ya filtrados por
// dominio público + piso de descubrimiento (1920px). Sin descargar.
import { getJSON, measureRemote } from './lib.mjs';
import { UA } from './resolve.mjs';
import { MET_SUBJECTS, MET_DEPTS_PREF, WMC_CATEGORIES } from './targets-01.mjs';

const DISCOVERY_FLOOR = 1920; // Full HD+ preferido en descubrimiento

// ---------------- MET ----------------
export async function discoverMet({ perSubject = 12, floor = DISCOVERY_FLOOR, onLog,
  subjects = MET_SUBJECTS, depts = MET_DEPTS_PREF, dateMin, dateMax, matchArtist = false, exclude = null } = {}) {
  const seenId = new Set();
  const out = [];
  for (const subj of subjects) {
    let s;
    try { s = await getJSON(`https://collectionapi.metmuseum.org/public/collection/v1/search?q=${encodeURIComponent(subj)}&hasImages=true`, { ua: UA, delay: 110 }); }
    catch { continue; }
    const ids = (s.objectIDs || []).slice(0, perSubject);
    for (const id of ids) {
      if (seenId.has(id)) continue; seenId.add(id);
      let o;
      try { o = await getJSON(`https://collectionapi.metmuseum.org/public/collection/v1/objects/${id}`, { ua: UA, delay: 80 }); }
      catch { continue; }
      if (!o.isPublicDomain || !o.primaryImage) continue;
      if (!depts.has(o.department)) continue;
      // Filtro de época (cuando se pide): la obra debe caer en la ventana de fechas.
      if (dateMin != null && (o.objectEndDate || o.objectBeginDate) < dateMin) continue;
      if (dateMax != null && (o.objectBeginDate || o.objectEndDate) > dateMax) continue;
      // Relevancia: el término debe aparecer en título/cultura/clasif/tags (+ autor si matchArtist)
      const hay = ((o.title || '') + ' ' + (o.culture || '') + ' ' + (o.classification || '')
        + ' ' + (o.period || '') + ' ' + (matchArtist ? (o.artistDisplayName || '') : '')
        + ' ' + ((o.tags || []).map(t => t.term).join(' '))).toLowerCase();
      if (!hay.includes(subj.toLowerCase())) continue;
      if (exclude && exclude.test(hay)) { onLog?.({ stage: 'met-discovery', reason: 'excluded', id, title: o.title }); continue; }
      const m = await measureRemote(o.primaryImage, { ua: UA });
      const long = Math.max(m.w, m.h);
      if (long < floor) { onLog?.({ stage: 'met-discovery', reason: 'low_res', long, id, title: o.title }); continue; }
      out.push({
        museum: 'The Met', sourceId: String(o.objectID),
        title: o.title, artist: o.artistDisplayName || (o.culture || 'Anonimo'),
        year: o.objectDate || '', classification: o.classification || o.objectName || '',
        license: 'Public Domain', source_url: o.objectURL, image_url: o.primaryImage,
        w: m.w, h: m.h, mime: 'image/jpeg', preBuffer: m.fullBuffer,
        subject: subj, kind: 'discovery',
      });
    }
  }
  return out;
}

// ---------------- WIKIMEDIA ----------------
const PD_OK = (em) => {
  const lic = (em?.License?.value || '').toLowerCase();
  const short = (em?.LicenseShortName?.value || '').toLowerCase();
  if (lic === 'cc0' || lic === 'pd' || lic.startsWith('pd-')) return true;
  if (/public domain|cc0/.test(short)) return true;
  if ((em?.Copyrighted?.value || '').toLowerCase() === 'false') return true;
  return false;
};
const BAD = /\b(detail|crop|fragment|copy|engrav|etching|sketch|reverse|x-ray|frame|verso|signature|gasometer|installation|exhibition|replica|poster|billboard|interior|map|coin|seal|glaspalast|catalogue|katalog|halftone|immortali[sz]ed|collage|wikidata|facsimiles?|wasserman|wallis budge|published by|photographed by|conservator|library of congress)\b/i;
// Veneno "moderno": arte digital/IA/render que se cuela por categorías temáticas amplias.
const MODERN = /(exoplanet|science[ -]fantasy|sci-fi|\bcgi\b|digital (art|painting|illustration)|ai[ .-]?generated|generated by (ai|midjourney|an? )|midjourney|stable diffusion|dall.e|photomanip|deviantart|concept art|prototyperspective|\b3d\b|render(ing)? of|video ?game|screenshot)/i;
// Títulos basura: códigos de foto de museo ("budapest kunst 0036"), collages, sin letras reales.
const JUNK_TITLE = (s) => /\bkunst\s*\d|immortali[sz]ed by the masters|\bcollage\b/i.test(s) || !/[a-z]{4,}/i.test(s);
const strip = (s) => (s || '').replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
// Limpia marcado Wikibase/Wikidata de los títulos: extrae el label inglés de
// `... title QS:P1476,en:"Apollo's Enchantment" ...`; si no, quita el marcado QS.
function cleanLabel(s) {
  s = strip(s);
  if (!s) return '';
  const m = s.match(/en:"([^"]+)"/);
  if (m) return m[1].trim();
  return s.replace(/\b(title|label)\s+QS:[^,]*,?/gi, ' ')
          .replace(/QS:[A-Za-z0-9:,.]+/g, ' ')
          .replace(/[",]+/g, ' ').replace(/\s+/g, ' ').trim();
}

async function imageInfoBatch(titles) {
  const out = [];
  for (let i = 0; i < titles.length; i += 20) {
    const chunk = titles.slice(i, i + 20);
    const u = 'https://commons.wikimedia.org/w/api.php?action=query&format=json&prop=imageinfo'
      + '&iiprop=url|size|mime|extmetadata&iiurlwidth=8000&titles=' + encodeURIComponent(chunk.join('|'));
    try { const j = await getJSON(u, { ua: UA, delay: 120 }); out.push(...Object.values(j.query?.pages || {})); }
    catch { /* skip chunk */ }
  }
  return out;
}

export async function discoverWMC({ perCat = 40, floor = DISCOVERY_FLOOR, onLog, categories = WMC_CATEGORIES, exclude = null, maxYear = null } = {}) {
  const seen = new Set();
  const out = [];
  for (const cat of categories) {
    let cm;
    try {
      cm = await getJSON('https://commons.wikimedia.org/w/api.php?action=query&format=json&list=categorymembers'
        + '&cmtype=file&cmlimit=' + perCat + '&cmtitle=' + encodeURIComponent('Category:' + cat), { ua: UA, delay: 120 });
    } catch { continue; }
    const titles = (cm.query?.categorymembers || []).map(m => m.title).filter(t => !seen.has(t));
    titles.forEach(t => seen.add(t));
    const pages = await imageInfoBatch(titles);
    for (const p of pages) {
      const ii = p.imageinfo?.[0]; if (!ii) continue;
      const em = ii.extmetadata || {};
      if (!PD_OK(em)) continue;
      const fname = (p.title || '').toLowerCase();
      if (BAD.test(fname) || MODERN.test(fname) || JUNK_TITLE(fname)) continue;
      let w = ii.width, h = ii.height;
      if (!w || !h) continue;
      const long = Math.max(w, h);
      if (long < floor) { onLog?.({ stage: 'wmc-discovery', reason: 'low_res', long, title: p.title }); continue; }
      // URL: jpeg original, o render a <=8000 si es más grande o no-jpeg
      let url = ii.url, mime = ii.mime;
      if (mime !== 'image/jpeg' || long > 8000) {
        if (ii.thumburl) { url = ii.thumburl; w = ii.thumbwidth; h = ii.thumbheight; mime = 'image/jpeg'; }
      }
      const objName = cleanLabel(em.ObjectName?.value);
      const imgDesc = cleanLabel(em.ImageDescription?.value);
      const fnameTitle = p.title.replace(/^File:/, '').replace(/\.[a-z]+$/i, '').replace(/[_]+/g, ' ').trim();
      // Volcado multilingüe de Wikidata ("Spanish: ... German: ...title...") = ilegible.
      // En ese caso preferimos el nombre de archivo, que suele ser coherente.
      const isMessy = (s) => !s || /\b(german|spanish|dutch|french|italian|latin|russian|polish|portuguese|czech|swedish|english)\s*:/i.test(s) || /[a-z](title|label)\b/i.test(s) || /\bQS:/i.test(s);
      const title = [objName, fnameTitle, imgDesc.slice(0, 70)].find(s => s && !isMessy(s)) || fnameTitle || objName;
      if (JUNK_TITLE(title)) { onLog?.({ stage: 'wmc-discovery', reason: 'junk_title', title: p.title }); continue; }
      const artist = cleanLabel(em.Artist?.value) || 'Anonimo';
      const rawYear = strip(em.DateTimeOriginal?.value) || '';
      if (MODERN.test(`${title} ${artist} ${imgDesc}`)) { onLog?.({ stage: 'wmc-discovery', reason: 'modern', title: p.title }); continue; }
      // descartar lo posterior a la época; CONSCIENTE de a.C. (no rechaza artefactos BC/BCE)
      if (maxYear && !/\bb\.?\s*c\.?e?\b/i.test(`${rawYear} ${title} ${fname}`)) {
        const m = rawYear.match(/\b(1\d{3}|20\d{2})\b/) || `${title} ${fname}`.match(/\b(20\d{2})\b/);
        if (m && +m[1] > maxYear) { onLog?.({ stage: 'wmc-discovery', reason: 'too_modern', year: m[1], title: p.title }); continue; }
      }
      if (exclude && exclude.test(fname + ' ' + title + ' ' + imgDesc)) { onLog?.({ stage: 'wmc-discovery', reason: 'excluded', title: p.title }); continue; }
      out.push({
        museum: 'Wikimedia', sourceId: p.title,
        title, artist, year: rawYear,
        classification: 'painting', license: strip(em.LicenseShortName?.value) || 'Public domain',
        source_url: 'https://commons.wikimedia.org/wiki/' + encodeURIComponent(p.title),
        image_url: url, w, h, mime, kind: 'discovery',
      });
    }
  }
  return out;
}
